import { test, expect } from '@playwright/test'
import { apiCreateForm, apiPublish, uniq } from './helpers'
import { emptyForm, newBlock } from '../../engine/forms/core/index'

test.describe('Forms home', () => {
  test('new form opens the builder; the list shows state; rename, duplicate, filter, delete', async ({ page, request }) => {
    const liveTitle = uniq('Live one')
    const def = emptyForm(liveTitle)
    def.pages[0].blocks.push(newBlock('short', { label: 'Name' }))
    const live = await apiCreateForm(request, { title: liveTitle, definition: def })
    await apiPublish(request, live.id)
    await page.goto('/forms')
    await page.getByTestId('new-form').click()
    await expect(page).toHaveURL(/\/forms\/frm_[a-z0-9]+\?new=1/)
    await expect(page.getByTestId('form-title')).toHaveValue('Untitled form')
    const draftTitle = uniq('Renamed in builder')
    await page.getByTestId('form-title').fill(draftTitle)
    await expect(page.getByTestId('save-state')).toHaveText(/Saved/, { timeout: 15_000 })
    await page.getByRole('button', { name: 'Back to Forms' }).click()
    await expect(page).toHaveURL(/\/forms$/)
    const rows = page.getByTestId('form-row')
    await expect(rows.filter({ hasText: draftTitle })).toHaveCount(1)
    await expect(rows.filter({ hasText: liveTitle }).getByTestId('form-state')).toHaveText('Live')
    await expect(rows.filter({ hasText: draftTitle }).getByTestId('form-state')).toHaveText('Draft')
    await page.getByRole('radio', { name: 'Live' }).click()
    await expect(rows.filter({ hasText: draftTitle })).toHaveCount(0)
    await expect(rows.filter({ hasText: liveTitle })).toHaveCount(1)
    await page.getByRole('radio', { name: 'All' }).click()
    await page.getByLabel('Search forms').fill(liveTitle.slice(-6))
    await expect(rows).toHaveCount(1)
    await page.getByLabel('Search forms').fill('')
    const row = rows.filter({ hasText: liveTitle })
    await row.getByTestId('form-menu').click()
    await page.getByTestId('menu-rename').click()
    const rename = page.getByRole('textbox', { name: 'Form name' })
    await rename.fill(`${liveTitle} renamed`)
    await rename.press('Enter')
    await expect(rows.filter({ hasText: `${liveTitle} renamed` })).toHaveCount(1)
    await rows.filter({ hasText: `${liveTitle} renamed` }).getByTestId('form-menu').click()
    await page.getByTestId('menu-duplicate').click()
    await expect(rows.filter({ hasText: `${liveTitle} renamed` })).toHaveCount(2)
    const copy = rows.filter({ hasText: 'copy' }).first()
    await expect(copy.getByTestId('form-state')).toHaveText('Draft')
    await copy.getByTestId('form-menu').click()
    await page.getByTestId('menu-delete').click()
    await expect(page.getByTestId('confirm')).toBeVisible()
    await page.getByTestId('confirm-yes').click()
    await expect(rows.filter({ hasText: `${liveTitle} renamed` })).toHaveCount(1)
    const [popup] = await Promise.all([page.waitForEvent('popup'), rows.filter({ hasText: `${liveTitle} renamed` }).getByTestId('form-title').click({ modifiers: ['Control'] })])
    await expect(popup).toHaveURL(/\/forms\/responses\?form=frm_/)
    await expect(popup.getByTestId('results-tab')).toBeVisible()
  })
})

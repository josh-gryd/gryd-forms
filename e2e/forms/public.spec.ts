import { test, expect, devices } from '@playwright/test'
import { apiCreateForm, apiPublish, apiGetForm, BASE, axeCheck } from './helpers'
import { seedComplexForm } from '../../engine/forms/core/index'

async function seededLive(request: Parameters<typeof apiCreateForm>[0]) {
  const def = seedComplexForm()
  const f = await apiCreateForm(request, { title: def.title, definition: def })
  const pub = await apiPublish(request, f.id)
  return { id: f.id, slug: pub.slug, def, version: pub.version }
}

const ids = (def: ReturnType<typeof seedComplexForm>) => {
  const p1 = def.pages[0], p2 = def.pages[1]
  return {
    first: p1.blocks.find(b => b.label === 'First name')!.id, last: p1.blocks.find(b => b.label === 'Last name')!.id, email: p1.blocks.find(b => b.label === 'Work email')!.id,
    company: p1.blocks.find(b => b.label === 'Company')!.id, size: p1.blocks.find(b => b.label === 'Company size')!, role: p2.blocks.find(b => b.type === 'choice')!, fix: p2.blocks.find(b => b.type === 'long')!.id,
  }
}


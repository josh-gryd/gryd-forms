  test('submit is idempotent and durable: a double click stores one response; a retry after a network failure keeps the same key', async ({ page, request }) => {
    const live = await seededLive(request)
    const b = ids(live.def)
    await page.goto(`/f/${live.slug}`)
    await page.locator(`#in-${b.first}`).fill('Idem')
    await page.locator(`#in-${b.last}`).fill('Potent')
    await page.locator(`#in-${b.email}`).fill('idem@example.com')
    await page.locator(`#in-${b.company}`).fill('Twice')
    await page.locator(`#in-${b.size.id}`).selectOption(b.size.options[0].id)
    await page.getByTestId('continue').click()
    await page.getByRole('radio', { name: b.role.options[0].label }).check()
    await page.locator(`#in-${b.fix}`).fill('x')
    await page.getByTestId('continue').click()
    // first attempt: the network drops after the request leaves
    let failed = 0
    await page.route('**/api/public/forms/*/submit', route => { failed += 1; route.abort('failed') })
    await page.getByTestId('continue').click()
    await expect(page.getByTestId('submit-failed')).toBeVisible()
    expect(failed).toBe(1)
    await page.unroute('**/api/public/forms/*/submit')
    let keys: string[] = []
    page.on('request', r => { if (r.url().includes('/submit') && r.method() === 'POST') keys.push(JSON.parse(r.postData() || '{}').idempotencyKey) })
    await page.getByTestId('submit-failed').getByRole('button', { name: 'Try again' }).click()
    await page.getByTestId('continue').click({ force: true, noWaitAfter: true }).catch(() => undefined)
    await expect(page.getByTestId('ending')).toBeVisible()
    const list = await request.get(`${BASE}/api/forms/${live.id}/responses?status=all`)
    expect((await list.json()).total).toBe(1)
    expect(new Set(keys).size).toBeLessThanOrEqual(1)
  })


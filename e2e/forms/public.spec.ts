  test('closed form shows the closed message; an unknown slug is a 404', async ({ page, request }) => {
    const live = await seededLive(request)
    const close = await request.post(`${BASE}/api/forms/${live.id}/close`, { data: {} })
    expect(close.ok()).toBeTruthy()
    await request.patch(`${BASE}/api/forms/${live.id}`, { data: { closedMessage: 'Applications closed for this cohort.' } })
    await page.goto(`/f/${live.slug}`)
    await expect(page.getByTestId('form-closed')).toContainText('Applications closed for this cohort.')
    await expect(page.getByTestId('continue')).toHaveCount(0)
    const res = await page.goto('/f/this-slug-does-not-exist')
    expect(res?.status()).toBe(404)
    await expect(page.getByTestId('form-unavailable')).toBeVisible()
    await request.post(`${BASE}/api/forms/${live.id}/reopen`, { data: {} })
    await page.goto(`/f/${live.slug}`)
    await expect(page.getByTestId('continue')).toBeVisible()
  })

  test('embed mode: no footer, reports its height to the host page', async ({ page, request }) => {
    const live = await seededLive(request)
    await page.goto('/f/this-slug-does-not-exist')
    const height = await page.evaluate(async (src) => new Promise<number>(resolve => {
      window.addEventListener('message', e => { if (e.data && e.data.source === 'gryd-forms' && e.data.type === 'height') resolve(e.data.height) })
      const f = document.createElement('iframe'); f.src = src; f.style.width = '700px'; document.body.appendChild(f)
    }), `/f/${live.slug}?embed=1`)
    expect(height).toBeGreaterThan(300)
    const frame = page.frames().find(fr => fr.url().includes('embed=1'))!
    await expect(frame.getByText('Made with GRYD Forms')).toHaveCount(0)
  })

  test('phone layout: columns stack, the primary button is full width, hit targets are 48px', async ({ browser, request }) => {
    const live = await seededLive(request)
    // Geometry, not motion: the page's 12px slide-in would move x between two measurements under load.
    const ctx = await browser.newContext({ ...devices['iPhone 14'], reducedMotion: 'reduce' })
    const page = await ctx.newPage()
    await page.goto(`${BASE}/f/${live.slug}`)
    const b = ids(live.def)
    const first = await page.locator(`#in-${b.first}`).boundingBox()
    const last = await page.locator(`#in-${b.last}`).boundingBox()
    expect(Math.abs(first!.x - last!.x)).toBeLessThan(2)
    expect(last!.y).toBeGreaterThan(first!.y + first!.height)
    expect(Math.round(first!.height)).toBe(48)
    const btn = await page.getByTestId('continue').boundingBox()
    const card = await page.getByTestId('form-page').boundingBox()
    expect(btn!.width).toBeGreaterThan(card!.width * 0.8)
    await ctx.close()
  })

  test('accessibility: the public form has labels, described-by wiring and no serious axe violations', async ({ page, request }) => {
    const live = await seededLive(request)
    const b = ids(live.def)
    await page.goto(`/f/${live.slug}`)
    await expect(page.locator(`label[for="in-${b.first}"]`)).toHaveCount(1)
    await page.getByTestId('continue').click()
    await expect(page.locator(`#in-${b.first}`)).toHaveAttribute('aria-describedby', new RegExp(`er-${b.first}`))
    const { serious } = await axeCheck(page)
    expect(serious.map(v => `${v.id}: ${v.nodes.map(n => n.target.join(' ')).join(', ')}`)).toEqual([])
  })

  test('the live link keeps serving the published version while the draft changes', async ({ page, request }) => {
    const live = await seededLive(request)
    const form = await apiGetForm(request, live.id)
    const draft = JSON.parse(JSON.stringify(form.draft))
    draft.pages[0].blocks[0].label = 'CHANGED IN DRAFT'
    const r = await request.put(`${BASE}/api/forms/${live.id}/draft`, { data: { definition: draft, baseRevision: form.revision } })
    expect(r.ok()).toBeTruthy()
    await page.goto(`/f/${live.slug}`)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Get your team set up')
    await apiPublish(request, live.id)
    await page.goto(`/f/${live.slug}`)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('CHANGED IN DRAFT')
  })

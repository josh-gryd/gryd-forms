import { test, expect } from '@playwright/test'
import { apiCreateForm, apiGetForm, openBuilder, ghostAdd, selectBlock, blockByLabel, waitSaved, uniq, publishFromBuilder, BASE, shellSidebar } from './helpers'
import { seedComplexForm } from '../../engine/forms/core/index'

test.describe('Logic, Theme, Share, Preview', () => {
  test('logic: rules render as sentences with slots; flow view; deleting a used field marks rules broken and blocks publishing', async ({ page, request }) => {
    const def = seedComplexForm()
    const f = await apiCreateForm(request, { title: def.title, definition: def })
    await openBuilder(page, f.id, 'logic')
    const cards = page.getByTestId('rule-card')
    await expect(cards).toHaveCount(3)
    await expect(cards.first().getByTestId('rule-sentence')).toContainText('When Company size is any of 51–200, 201–1,000, 1,000+, show page Enterprise questions.')
    await expect(cards.nth(2).getByTestId('cond-group')).toBeVisible()
    await page.getByRole('tab', { name: 'Flow' }).click()
    await expect(page.getByTestId('flow-view')).toBeVisible()
    await expect(page.getByTestId('flow-node-page')).toHaveCount(4)
    await expect(page.getByTestId('flow-node-ending')).toHaveCount(3)
    await page.getByTestId('flow-node-page').nth(2).click()
    await expect(page.getByTestId('tab-page-2')).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByTestId('canvas-page')).toHaveAttribute('aria-label', 'Enterprise questions')
    await page.getByTestId('tab-page-0').click()
    await selectBlock(page, 'Company size')
    await expect(page.getByTestId('logic-badge')).toBeVisible()
    await page.getByTestId('toolbar-delete').click()
    await expect(page.getByRole('status').filter({ hasText: 'rules need attention' })).toContainText('3 rules need attention')
    await expect(page.getByTestId('publish')).toBeDisabled()
    await page.getByTestId('tab-logic').click()
    await expect(page.getByTestId('rule-card').first()).toHaveAttribute('data-broken', 'true')
    await expect(page.getByTestId('rule-card').first().getByTestId('cond-field')).toHaveValue('')
    await page.getByTestId('tab-logic').focus()
    await page.keyboard.press('Control+z')
    await expect(page.getByTestId('rule-card').first()).not.toHaveAttribute('data-broken', 'true')
    await expect(page.getByTestId('publish')).toBeEnabled()
    await waitSaved(page)
  })

  test('logic: "Rule using this field" from the inspector pre-fills the condition; the sentence updates live', async ({ page, request }) => {
    const f = await apiCreateForm(request, { title: uniq('Rules') })
    await openBuilder(page, f.id)
    await ghostAdd(page, 'Do you like forms?')
    await page.getByTestId('add-page').click()
    await page.getByTestId('tab-page-0').click()
    await selectBlock(page, 'Do you like forms?')
    await page.getByTestId('insp-logic').locator('summary').click()
    await page.getByTestId('insp-add-rule').click()
    await expect(page.getByTestId('logic-tab')).toBeVisible()
    const card = page.getByTestId('rule-card').first()
    await expect(card.getByTestId('cond-field')).toHaveValue(/b_/)
    await card.getByRole('textbox', { name: 'Value' }).fill('yes')
    await expect(card.getByTestId('rule-sentence')).toContainText('When Do you like forms? is yes, show page Page 2.')
    await card.getByTestId('rule-action').selectOption('go_to_ending')
    await expect(card.getByTestId('rule-sentence')).toContainText('end with Thanks')
    await page.getByTestId('tab-build').click()
    await selectBlock(page, 'Do you like forms?')
    await expect(page.getByTestId('insp-logic')).toContainText('1 rule')
    await waitSaved(page)
    const saved = await apiGetForm(request, f.id)
    expect(saved.draft.rules.length).toBe(1)
    expect(saved.draft.rules[0].then.type).toBe('go_to_ending')
  })

  test('theme: presets restyle the canvas; a failing contrast pair warns and Fix resolves it', async ({ page, request }) => {
    const def = seedComplexForm()
    const f = await apiCreateForm(request, { title: def.title, definition: def })
    await openBuilder(page, f.id, 'theme')
    await page.getByTestId('preset-ink').click()
    const card = page.getByTestId('canvas-page')
    await expect(card).toHaveCSS('background-color', 'rgb(30, 29, 24)')
    await page.getByTestId('colour-text').evaluate((el: HTMLInputElement) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!; set.call(el, '#1e1d18'); el.dispatchEvent(new Event('input', { bubbles: true })) })
    await expect(page.getByRole('status').filter({ hasText: /:1\)/ }).first()).toBeVisible()
    await page.getByRole('button', { name: 'Fix' }).first().click()
    await waitSaved(page)
    const saved = await apiGetForm(request, f.id)
    expect(saved.draft.theme.text).not.toBe('#1e1d18')
    expect(saved.draft.theme.bg).toBe('#161616')
  })

  test('publish moment, changes-not-published, accept responses, link name', async ({ page, request }) => {
    const f = await apiCreateForm(request, { title: uniq('Publish') })
    await openBuilder(page, f.id)
    await ghostAdd(page, 'Your name')
    await expect(page.getByTestId('publish-state')).toHaveText('Draft')
    await publishFromBuilder(page)
    await expect(page.getByTestId('publish-state')).toHaveText('Live')
    await expect(page.getByTestId('publish')).toHaveText('Published')
    await ghostAdd(page, 'Your email')
    await waitSaved(page)
    await expect(page.getByTestId('publish-state')).toHaveText('Unpublished edits')
    await expect(page.getByTestId('publish')).toHaveText('Publish changes')
    await page.getByTestId('tab-share').click()
    const slug = (await apiGetForm(request, f.id)).slug
    await expect(page.getByTestId('share-url')).toContainText(`/f/${slug}`)
    // Accept responses lives in Settings › Availability; Share links there.
    await page.getByTestId('share-open-settings').click()
    await expect(page.getByTestId('settings-accept')).toHaveAttribute('aria-checked', 'true')
    await page.getByTestId('settings-accept').click()
    await expect(page.getByTestId('publish-state')).toHaveText('Closed')
    const closed = await request.get(`${BASE}/api/public/forms/by-slug/${slug}`)
    expect((await closed.json()).status).toBe('closed')
    await page.getByTestId('settings-accept').click()
    await expect(page.getByTestId('publish-state')).toHaveText('Unpublished edits')
    await page.getByTestId('tab-share').click()
    const newSlug = `link-${Date.now().toString(36)}`
    await page.getByTestId('share-slug').fill(newSlug)
    await page.getByTestId('share-slug-save').click()
    await expect(page.getByTestId('share-url')).toContainText(`/f/${newSlug}`)
    const res = await request.get(`${BASE}/f/${newSlug}`)
    expect(res.status()).toBe(200)
    await page.getByTestId('share-publish').click()
    await expect(page.getByTestId('toast-published')).toBeVisible()
    await expect(page.getByTestId('publish-state')).toHaveText('Live')
    const versions = (await apiGetForm(request, f.id)).versions
    expect(versions.length).toBe(2)
  })

  test('preview: ⌘↵ opens it from the first page even with page 2 selected, devices frame the form, answers are never saved', async ({ page, request }) => {
    const def = seedComplexForm()
    const f = await apiCreateForm(request, { title: def.title, definition: def })
    await openBuilder(page, f.id)
    await page.getByTestId('tab-page-1').click()
    await page.keyboard.press('Control+Enter')
    await expect(page.getByTestId('preview-mode')).toBeVisible()
    // Preview is the respondent's walk: it never starts past a page (QA 2026-09-24).
    await expect(page.getByTestId('form-page')).toHaveAttribute('aria-label', 'About you')
    await page.getByTestId('device-phone').click()
    const frame = page.getByTestId('preview-frame-phone')
    await expect(frame).toBeVisible()
    await expect.poll(async () => Math.round((await frame.boundingBox())!.width)).toBe(392)
    await page.getByTestId('device-desktop').click()
    await page.getByTestId('preview-restart').click()
    await expect(page.getByTestId('form-page')).toHaveAttribute('aria-label', 'About you')
    const b = def.pages[0].blocks
    await page.locator(`#in-${b[2].id}`).fill('Pre')
    await page.locator(`#in-${b[3].id}`).fill('View')
    await page.locator(`#in-${b[4].id}`).fill('p@example.com')
    await page.locator(`#in-${b[6].id}`).fill('Co')
    await page.locator(`#in-${b[7].id}`).selectOption(b[7].options[0].id)
    await page.getByTestId('continue').click()
    await page.getByRole('radio', { name: 'Founder or CEO' }).check()
    await page.locator(`#in-${def.pages[1].blocks[1].id}`).fill('x')
    await page.getByTestId('continue').click()
    await page.getByTestId('continue').click()
    await expect(page.getByTestId('ending')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('preview-mode')).toHaveCount(0)
    const list = await (await request.get(`${BASE}/api/forms/${f.id}/responses?status=all`)).json()
    expect(list.total).toBe(0)
  })

  test('responsive: the sidebar holds 288 and the bar stays centred down to 1000; below that the builder hands over to a read-only preview', async ({ page, request }) => {
    const f = await apiCreateForm(request, { title: uniq('Narrow') })
    await page.setViewportSize({ width: 1100, height: 800 })
    await openBuilder(page, f.id)
    await ghostAdd(page, 'Narrow question')
    const side = shellSidebar(page)
    const centred = async () => {
      const bar = (await page.getByTestId('section-bar').boundingBox())!
      const region = (await page.getByTestId('builder-region').boundingBox())!
      const s = (await side.boundingBox())!
      expect(Math.abs(bar.x + bar.width / 2 - (region.x + region.width / 2))).toBeLessThan(2)
      expect(bar.x).toBeGreaterThanOrEqual(s.x + s.width)
      expect(bar.y + bar.height).toBeLessThan((await page.getByTestId('page-strip').boundingBox())!.y)
    }
    // the shell narrows every other app's sidebar to 204 at ≤1100; the builder's stays 288
    expect((await side.boundingBox())!.width).toBe(288)
    await centred()
    await expect(page.getByTestId('field-panel')).toBeVisible()
    // narrower than 1280 the bar keeps words only on the open section
    await expect(page.getByTestId('tab-logic').locator('.fb-seg__txt')).toBeHidden()
    await expect(page.getByTestId('tab-build').locator('.fb-seg__txt')).toBeVisible()
    await page.setViewportSize({ width: 1000, height: 800 })
    expect((await side.boundingBox())!.width).toBe(288)
    await centred()
    await expect(blockByLabel(page, 'Narrow question')).toHaveCount(1)
    await page.setViewportSize({ width: 900, height: 800 })
    await expect(page.getByText('Open on a larger screen to build')).toBeVisible()
    await expect(side).toBeHidden()
    await expect(blockByLabel(page, 'Narrow question')).toHaveCount(0)
    await expect(page.getByTestId('builder-band')).toBeVisible()
    // The other sections still open there
    await page.getByTestId('tab-share').click()
    await expect(page.getByTestId('share-tab')).toBeVisible()
    // At phone width the builder hands over to the phone view (read-only questions).
    await page.setViewportSize({ width: 600, height: 800 })
    await expect(page.getByText('Open on desktop', { exact: false })).toBeVisible()
  })
})

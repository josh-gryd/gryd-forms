  test('availability at the door: a response limit, then not open yet, then a closing date passed', async ({ page, request }) => {
    const f = await liveForm(request, uniq('Door'))
    const [n, e] = f.def.pages[0].blocks
    await settings(request, f.id, { ops: { maxResponses: 1 } })
    expect((await apiSubmit(request, f.id, { [n.id]: 'One', [e.id]: 'one@example.com' })).status).toBe(200)
    await page.goto(`/f/${f.slug}`)
    await expect(page.getByTestId('form-closed-body')).toHaveText('This form has all the responses it needs. Thanks for your interest.')
    await shot(page, 'public-limit')
    await settings(request, f.id, { ops: { maxResponses: null, opensAt: new Date(Date.now() + 3 * 86400_000).toISOString(), timezone: 'Europe/London' } })
    await page.goto(`/f/${f.slug}`)
    await expect(page.getByTestId('form-scheduled-body')).toContainText('This form opens on')
    await shot(page, 'public-scheduled')
    await settings(request, f.id, { ops: { opensAt: null, closesAt: new Date(Date.now() - 60_000).toISOString() } })
    await page.goto(`/f/${f.slug}`)
    await expect(page.getByTestId('form-closed')).toBeVisible()
  })


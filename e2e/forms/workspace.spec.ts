    // The summary hands focus to the first field a beat later; typing before it lands can go astray.
    await expect(page.locator(`#in-${n.id}`)).toBeFocused()
    await page.locator(`#in-${n.id}`).fill('Ana')
    await page.locator(`#in-${e.id}`).fill('ana@example.com')
    await page.getByTestId('continue').click()
    await expect(page.getByTestId('back')).toHaveCount(0)
    await page.getByText('Pro', { exact: true }).click()
    await expect(page.getByTestId('continue')).toContainText('Enviar')
    await page.getByTestId('continue').click()
    await expect(page.getByTestId('edit-link')).toContainText('Editar tu respuesta')
    await expect(page.getByTestId('ending').locator('h1')).toHaveText('Gracias, lo hemos recibido.')
    await shot(page, 'public-es-ending-edit-link')
    const editHref = await page.getByTestId('edit-link-open').getAttribute('href')
